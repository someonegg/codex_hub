export type Namespace = "common" | keyof typeof namespaceKeys;
export const namespaceFor = new Map<string, Namespace>(
  Object.entries(namespaceKeys).flatMap(([namespace, keys]) =>
    keys.map((key) => [key, namespace as Namespace] as const),
  ),
);
export function partitionMessages(messages: Record<keyof typeof en, string>) {
  const result: Record<Namespace, Record<string, string>> = {
    common: {},
    hub: {},
    reader: {},
    interaction: {},
    hosting: {},
    errors: {},
  };
  for (const [key, message] of Object.entries(messages)) {
    const namespace = namespaceFor.get(key) ?? "common";
    result[namespace][key] = message;
  }
  return result;
}
